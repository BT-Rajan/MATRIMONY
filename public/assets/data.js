function fillSelect(select, options, selected) {
    select.innerHTML = '<option value="">-- தேர்வு செய்யவும் --</option>' +
        options.map(o => `<option value="${o}" ${o === selected ? 'selected' : ''}>${o}</option>`).join('');
}
